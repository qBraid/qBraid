"""
Generate the Pauli-operator conversion packages under ``qbraid/transpiler/conversions/``.

Every canonical operator library converts directly to every other one, and each such
conversion is the one-liner ``write_<target>(read_<source>(op))`` over the readers and
writers in ``conversions/_pauli_io.py``. That is n * (n - 1) functions spread across n
packages, so adding a library touches every other package. This script writes all of
them from the table below; edit the table, then run::

    python bin/generate_operator_conversions.py

``tests/transpiler/operators/test_operator_codegen.py`` fails if the committed packages
differ from what this script writes, or if a library is missing a reader, writer or
registry entry.

Feeder aliases (a library's other user-facing types, e.g. Cirq's ``PauliString``) have
one hand-written edge into their canonical form and are not generated here.
"""
from __future__ import annotations

import pathlib
import sys
from typing import NamedTuple

REPO = pathlib.Path(__file__).resolve().parent.parent
CONVERSIONS = REPO / "qbraid" / "transpiler" / "conversions"
LINE_LENGTH = 100

HEADER = (
    (REPO / "qbraid" / "transpiler" / "conversions" / "__init__.py").read_text().split('"""', 1)[0]
)


class Library(NamedTuple):
    """How one canonical operator type is named in generated code and docs."""

    display: str  # for docstrings, e.g. "Qiskit ``SparsePauliOp``"
    annotation: str  # the type as written in signatures
    type_import: str  # the TYPE_CHECKING import that makes ``annotation`` resolve


# Canonical operator libraries. Each needs read_<alias> / write_<alias> in _pauli_io.py
# and an entry in OPERATOR_TYPES (qbraid/programs/_import.py).
LIBRARIES: dict[str, Library] = {
    "qiskit_pauli": Library(
        "Qiskit ``SparsePauliOp``",
        "SparsePauliOp",
        "from qiskit.quantum_info import SparsePauliOp",
    ),
    "openfermion_qubit": Library(
        "OpenFermion ``QubitOperator``", "openfermion.QubitOperator", "import openfermion"
    ),
    "cirq_pauli": Library("Cirq ``PauliSum``", "cirq.PauliSum", "import cirq"),
    "pennylane_pauli": Library(
        "PennyLane ``PauliSentence``", "pennylane.pauli.PauliSentence", "import pennylane"
    ),
    "braket_observable": Library(
        "Amazon Braket ``Observable``",
        "braket.circuits.observable.Observable",
        "import braket.circuits.observable",
    ),
    "cudaq_spin": Library("CUDA-Q ``SpinOperator``", "cudaq.SpinOperator", "import cudaq"),
}


def _article(text: str) -> str:
    return "an" if text[0] in "AEIOU" else "a"


def _function(source: str, target: str) -> str:
    src, tgt = LIBRARIES[source], LIBRARIES[target]
    name = f"{source}_to_{target}"
    signature = f"def {name}(op: {src.annotation}) -> {tgt.annotation}:"
    if len(signature) > LINE_LENGTH:
        signature = f"def {name}(\n    op: {src.annotation},\n) -> {tgt.annotation}:"
    return (
        "@weight(1)\n"
        f"{signature}\n"
        f'    """Convert {_article(src.display)} {src.display} to '
        f'{_article(tgt.display)} {tgt.display}."""\n'
        f"    return write_{target}(read_{source}(op))\n"
    )


def _imports(source: str, targets: list[str]) -> str:
    """TYPE_CHECKING imports in isort order: plain imports, then from-imports."""
    lines = {LIBRARIES[alias].type_import for alias in [source, *targets]}
    plain = sorted(line for line in lines if line.startswith("import "))
    from_ = sorted(line for line in lines if line.startswith("from "))
    return "".join(f"    {line}\n" for line in plain + from_)


def render_package(source: str) -> dict[pathlib.Path, str]:
    """The ``__init__.py`` and ``<source>_extras.py`` for one canonical library."""
    targets = sorted(alias for alias in LIBRARIES if alias != source)
    names = [f"{source}_to_{target}" for target in targets]
    helpers = sorted([f"read_{source}", *(f"write_{target}" for target in targets)])
    display = LIBRARIES[source].display
    package = CONVERSIONS / source

    extras = (
        HEADER + '"""\n'
        f"Module defining conversions from {display} to the other Pauli-operator types.\n\n"
        "Generated by ``bin/generate_operator_conversions.py``; edit that script, not this file.\n"
        "\n"
        '"""\n'
        "from __future__ import annotations\n\n"
        "from typing import TYPE_CHECKING\n\n"
        "from qbraid.transpiler.annotations import weight\n"
        "from qbraid.transpiler.conversions._pauli_io import (\n"
        + "".join(f"    {helper},\n" for helper in helpers)
        + ")\n\n"
        "if TYPE_CHECKING:\n"
        + _imports(source, targets)
        + "\n\n"
        + "\n\n".join(_function(source, target) for target in targets)
    )
    init = (
        HEADER + '"""\n'
        f"Conversions from {display}.\n\n"
        f".. currentmodule:: qbraid.transpiler.conversions.{source}\n\n"
        ".. autosummary::\n"
        "   :toctree: ../stubs/\n\n" + "".join(f"   {name}\n" for name in names) + '\n"""\n'
        f"from .{source}_extras import (\n" + "".join(f"    {name},\n" for name in names) + ")\n\n"
        "__all__ = [\n" + "".join(f'    "{name}",\n' for name in names) + "]\n"
    )
    return {package / "__init__.py": init, package / f"{source}_extras.py": extras}


def render() -> dict[pathlib.Path, str]:
    """Every generated file, keyed by path."""
    files: dict[pathlib.Path, str] = {}
    for source in LIBRARIES:
        files.update(render_package(source))
    return files


def main() -> None:
    """Write every generated package."""
    for path, text in render().items():
        path.parent.mkdir(exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"  wrote {path.relative_to(REPO)}")


if __name__ == "__main__":
    sys.exit(main())
